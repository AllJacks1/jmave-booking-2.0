import { addDaysToKey, manilaDateKey } from "@/lib/time";
import type { QuoteFormInput } from "./schema";

/** A fresh quotation form: tomorrow 9:00 AM for one day. */
export function newQuoteForm(
  kind: "quick" | "formal",
  fuelPrices: { gasoline: number; premium: number; diesel: number },
  now: Date = new Date(),
): QuoteFormInput {
  const start = addDaysToKey(manilaDateKey(now), 1);
  return {
    service: "self_drive",
    clientId: null,
    clientName: "",
    repeat: kind === "quick" ? "new" : "auto",
    vehicleId: null,
    bodyType: "sedan",
    category: "primo",
    startDate: start,
    startTime: "09:00",
    endDate: addDaysToKey(start, 1),
    endTime: "09:00",
    areaFrom: "Davao City",
    destination: "",
    notes: "",
    scheduleMode: "auto",
    hoursTier: 24,
    days: 1,
    additionalHoursBlock: null,
    extensionHours: 0,
    otPremiumSlot: "auto",
    beyondOperatingHours: false,
    withCdw: false,
    sevenDayDiscount: false,
    promo: "none",
    deliveryFee: 0,
    pickupFee: 0,
    includeFuel: true,
    deposit: 200_000,
    depositMethod: "cash",
    oneWayDistanceKm: 0,
    fuelPrices,
    reservationFee: 50_000,
    rentalMethod: "cash",
    reservationMethod: "cash",
    wdDays: 1,
    pricingBasis: "all_in",
    wdAdditionalHoursBlock: null,
    package: "round_trip",
    drivingTerm: "back_and_forth",
    driverRateMode: "contract_rate",
    event: "auto",
    clientType: "auto",
    corporateMarkupPct: 0,
    serviceArea: "davao_region",
    mealPerDay: 0,
    accommodationPerDay: 0,
    discount: 0,
    pickupPlace: "",
    dropoffPlace: "",
    itinerary: "",
    driverName: "",
    driverContact: "",
  };
}
